export const MENU_ITEMS: MenuItem[] = RAW_MENU_ITEMS.map((item) => {
  const tags: DietaryTag[] = [];
  const text = `${item.name} ${item.description || ''} ${item.urduName || ''}`.toLowerCase();
  
  const isVeg =
    item.category === 'juice_bar' ||
    text.includes('juice') ||
    text.includes('shake') ||
    text.includes('plain fries') ||
    text.includes('tea') ||
    text.includes('soda') ||
    text.includes('drink') ||
    text.includes('colada') ||
    text.includes('mineral water') ||
    text.includes('water bottle');

  if (isVeg) {
    tags.push('Veg');
  } else {
    tags.push('Halal');
  }

  const isSpicy =
    item.spiceLevel === 'Hot' ||
    item.spiceLevel === 'Karachi Spicy' ||
    text.includes('chutney') ||
    text.includes('zinger') ||
    text.includes('tikka') ||
    text.includes('bihari') ||
    text.includes('bbq') ||
    text.includes('chili') ||
    text.includes('masala') ||
    text.includes('jalfrezi') ||
    text.includes('manchurian') ||
    text.includes('szechuan') ||
    text.includes('hot & sour') ||
    text.includes('spicy');

  if (isSpicy) {
    tags.push('Spicy');
  }

  const isCrispy =
    text.includes('broast') ||
    text.includes('crispy') ||
    text.includes('zinger') ||
    text.includes('nugget') ||
    text.includes('wings') ||
    text.includes('fries');

  if (isCrispy) {
    tags.push('Crispy');
  }

  const isSpecial =
    item.isDeal ||
    item.popular ||
    text.includes('matka') ||
    text.includes('special') ||
    text.includes('famous') ||
    text.includes('combo');

  if (isSpecial) {
    tags.push('Chef Special');
  }

  return {
    ...item,
    dietaryTags: item.dietaryTags && item.dietaryTags.length > 0 ? item.dietaryTags : tags,
  };
});

